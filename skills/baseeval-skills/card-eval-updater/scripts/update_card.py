#!/usr/bin/env python3
"""Write rendered evaluation sections into a BPSW model card.

Edits are surgical and idempotent: only the `### Automated benchmark results`
subtree inside each evaluation section is written or replaced. Hand-written
prose in those sections is preserved and stays above the generated block.

Usage:
    update_card.py <card.md> <bundle.json> -o <out.md> [--dry-run]
    update_card.py --template <model-card.md> <bundle.json> -o <out.md>
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from card_text import (  # noqa: E402
    normalize_heading,
    scan_headings,
    section_span,
    split_frontmatter,
    subsection_span,
    trim_blank_edges,
)
from render_card_sections import (  # noqa: E402
    ANCHOR,
    SECTION_ORDER,
    render_metrics_frontmatter,
    render_sections,
)

# Cards generated by sync_and_classify_cards.py; edits here are overwritten.
GENERATED_DIRS = (
    "ai-resource-hub/_models",
    "ai-resource-hub/_agents",
    "ai-resource-hub/_framework",
)

EVAL_DETAILS_HEADING = "evaluation details"
ANCHOR_NORMALIZED = normalize_heading(ANCHOR.lstrip("#").strip())


class UpdateError(RuntimeError):
    pass


# --------------------------------------------------------------------------
# frontmatter
# --------------------------------------------------------------------------


def merge_metrics_frontmatter(frontmatter: str, entries: list[str]) -> tuple[str, list[str]]:
    """Merge `benchmark/metric` entries into the card's `metrics:` list.

    Existing entries are preserved (a card may legitimately track training-time
    metrics such as validation_loss alongside benchmark scores). Placeholder
    comment-only list items from the template are dropped.
    """
    lines = frontmatter.split("\n")
    start = None
    for idx, line in enumerate(lines):
        if re.match(r"^metrics\s*:\s*(#.*)?$", line):
            start = idx
            break

    if start is None:
        added = [e for e in entries]
        block = ["metrics:"] + [f"    - {e}" for e in entries]
        return "\n".join(lines + block), added

    end = start + 1
    existing: list[str] = []
    while end < len(lines):
        stripped = lines[end].strip()
        if not stripped:
            end += 1
            continue
        if not lines[end].startswith((" ", "\t")):
            break
        if stripped.startswith("-"):
            value = stripped.lstrip("-").strip()
            value = re.sub(r"\s*#.*$", "", value).strip().strip("\"'")
            if value:  # drop bare `- # comment` template placeholders
                existing.append(value)
            end += 1
            continue
        break

    added = [e for e in entries if e not in existing]
    merged = existing + added
    block = ["metrics:"] + [f"    - {e}" for e in merged]
    return "\n".join(lines[:start] + block + lines[end:]), added


# --------------------------------------------------------------------------
# body
# --------------------------------------------------------------------------


def _apply_section(
    body_lines: list[str], normalized_title: str, block: str
) -> tuple[list[str], str]:
    """Write `block` into a section. Returns (new_lines, action)."""
    headings = scan_headings(body_lines)
    outer = section_span(headings, body_lines, normalized_title)
    if outer is None:
        return body_lines, "missing"

    block_lines = block.split("\n")
    inner = subsection_span(headings, body_lines, outer, ANCHOR_NORMALIZED)

    if inner is not None:
        # Idempotent path: replace only the previously generated subtree.
        start, end = inner
        return body_lines[:start] + block_lines + [""] + body_lines[end:], "replaced"

    # First write: append after any existing prose so human text stays on top.
    start, end = outer
    existing = trim_blank_edges(body_lines[start:end])
    new_content = existing + ([""] if existing else []) + block_lines + [""]
    return body_lines[:start] + [""] + new_content + body_lines[end:], "appended"


def _ensure_sections(body_lines: list[str], missing: list[str]) -> list[str]:
    """Create absent evaluation subsections under `# Evaluation details`.

    Falls back to appending a whole `# Evaluation details` section when the card
    has none at all.
    """
    if not missing:
        return body_lines
    headings = scan_headings(body_lines)
    outer = section_span(headings, body_lines, EVAL_DETAILS_HEADING)
    new_headings = [f"## {title.title()}" for title in missing]

    if outer is None:
        tail = ["", "# Evaluation details", ""]
        for heading in new_headings:
            tail += [heading, ""]
        return body_lines + tail

    _, end = outer
    insert = []
    for heading in new_headings:
        insert += [heading, ""]
    return body_lines[:end] + insert + body_lines[end:]


def update_card(card_text: str, bundle: dict) -> tuple[str, dict]:
    frontmatter, body = split_frontmatter(card_text)
    body_lines = body.split("\n")
    sections = render_sections(bundle)

    report: dict = {"sections": {}, "metrics_added": [], "created_sections": []}

    # Two passes: create any missing sections first, then fill every section.
    missing = [
        name
        for name in SECTION_ORDER
        if section_span(scan_headings(body_lines), body_lines, name) is None
    ]
    if missing:
        body_lines = _ensure_sections(body_lines, missing)
        report["created_sections"] = missing

    for name in SECTION_ORDER:
        body_lines, action = _apply_section(body_lines, name, sections[name])
        report["sections"][name] = action

    if frontmatter is not None:
        frontmatter, added = merge_metrics_frontmatter(
            frontmatter, render_metrics_frontmatter(bundle)
        )
        report["metrics_added"] = added
        out = f"---\n{frontmatter}\n---\n" + "\n".join(body_lines)
    else:
        out = "\n".join(body_lines)

    out = re.sub(r"\n{4,}", "\n\n\n", out)
    if not out.endswith("\n"):
        out += "\n"
    return out, report


def check_output_path(path: Path) -> list[str]:
    warnings = []
    resolved = str(path.resolve())
    for generated in GENERATED_DIRS:
        if generated in resolved.replace("\\", "/"):
            warnings.append(
                f"{path} is inside {generated}, which sync_and_classify_cards.py "
                "regenerates from cards/resources/. Edit the raw card instead or this "
                "change will be overwritten."
            )
    return warnings


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("card", type=Path, nargs="?", help="card to update")
    ap.add_argument("bundle", type=Path, help="eval bundle from parse_eval_results.py")
    ap.add_argument(
        "--template",
        type=Path,
        help="start from the BPSW model-card template instead of an existing card",
    )
    ap.add_argument("-o", "--output", type=Path, help="write here (default: stdout)")
    ap.add_argument("--dry-run", action="store_true", help="show a diff, write nothing")
    args = ap.parse_args(argv)

    source = args.template or args.card
    if source is None:
        ap.error("provide a card path or --template")
    if not source.exists():
        print(f"error: {source} does not exist", file=sys.stderr)
        return 1

    bundle = json.loads(args.bundle.read_text(encoding="utf-8"))
    original = source.read_text(encoding="utf-8")
    updated, report = update_card(original, bundle)

    for name, action in report["sections"].items():
        if action == "missing":
            print(f"warning: section '{name}' could not be located or created", file=sys.stderr)
    if report["created_sections"]:
        print(
            "note: created missing sections: " + ", ".join(report["created_sections"]),
            file=sys.stderr,
        )
    if report["metrics_added"]:
        print(
            "note: added metrics frontmatter entries: " + ", ".join(report["metrics_added"]),
            file=sys.stderr,
        )

    if args.dry_run:
        diff = difflib.unified_diff(
            original.splitlines(keepends=True),
            updated.splitlines(keepends=True),
            fromfile=str(source),
            tofile=str(args.output or "<updated>"),
        )
        sys.stdout.writelines(diff)
        return 0

    if args.output:
        for warning in check_output_path(args.output):
            print(f"warning: {warning}", file=sys.stderr)
        args.output.write_text(updated, encoding="utf-8")
        print(f"wrote {args.output}", file=sys.stderr)
    else:
        sys.stdout.write(updated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
