def render_evaluation_data(bundle: dict) -> str:
    varied = _varied(bundle)
    rows = ["| Benchmark | Dataset | Items evaluated |", "|---|---|---|"]
    seen: set[tuple] = set()
    for r in bundle["results"]:
        # One row per benchmark/variant: a benchmark scored on several metrics
        # is still a single dataset.
        key = (r["benchmark"], r.get("variant"))
        if key in seen:
            continue
        seen.add(key)
        dataset = r.get("dataset_path") or r.get("task_yaml") or "—"
        if r.get("dataset_name"):
            dataset = f"{dataset} ({r['dataset_name']})"
        if r.get("num_samples") is not None and r.get("num_samples_total") is not None:
            count = f"{r['num_samples']:,} of {r['num_samples_total']:,}"
        elif r.get("num_samples") is not None:
            count = f"{r['num_samples']:,}"
        else:
            count = "—"
        if r.get("is_partial"):
            count += " *(partial)*"
        rows.append(f"| {_cell(_label(r, varied))} | {_cell(dataset)} | {count} |")
    body = ["\n".join(rows)]

    described: list[str] = []
    for r in bundle["results"]:
        note = r.get("dataset_description")
        if note and note not in described:
            described.append(note)
            body.append(f"**{_cell(r['benchmark'])}** — {note.strip()}")

    custom = [r for r in bundle["results"] if r.get("task_yaml")]
    if custom:
        body.append(
            "Task definitions for non-registered benchmarks: "
            + ", ".join(sorted({f"`{r['task_yaml']}`" for r in custom}))
            + "."
        )
    return "\n\n".join(body)


def render_evaluation_procedure(bundle: dict) -> str:
    run, model, compute = bundle["run"], bundle["model"], bundle.get("compute") or {}
    items: list[str] = []

    harness = run["harness"]
    if run.get("harness_version"):
        harness += f" v{run['harness_version']}"
    if run.get("framework"):
        harness += f" (framework: {run['framework']})"
    items.append(f"**Harness**: {harness}")

    model_bits = [f"`{model['id']}`"] if model.get("id") else ["not recorded"]
    if model.get("num_parameters"):
        model_bits.append(f"{model['num_parameters']:,} parameters")
    if model.get("dtype"):
        model_bits.append(str(model["dtype"]))
    if model.get("endpoint_url"):
        model_bits.append(f"served at {model['endpoint_url']}")
    if model.get("api_type"):
        model_bits.append(f"{model['api_type']} endpoint")
    items.append(f"**Model evaluated**: {', '.join(model_bits)}")

    shots = sorted(
        {r["num_fewshot"] for r in bundle["results"] if r.get("num_fewshot") is not None}
    )
    if shots:
        items.append(f"**Few-shot examples**: {', '.join(str(s) for s in shots)}")

    decoding = []
    for field, label in (
        ("temperature", "temperature"),
        ("top_p", "top_p"),
        ("max_new_tokens", "max new tokens"),
    ):
        values = sorted({r[field] for r in bundle["results"] if r.get(field) is not None})
        if values:
            decoding.append(f"{label} {', '.join(str(v) for v in values)}")
    items.append(
        f"**Decoding**: {'; '.join(decoding)}"
        if decoding
        else "**Decoding**: harness defaults (not recorded in the run artifacts)"
    )

    hardware = [str(v) for v in (compute.get("device"), compute.get("hardware_note")) if v]
    if compute.get("batch_size") is not None:
        hardware.append(f"batch size {compute['batch_size']}")
    if hardware:
        items.append(f"**Compute**: {', '.join(hardware)}")

    seeds = sorted({s for r in bundle["results"] for s in (r.get("seeds") or [])}, key=str)
    if seeds:
        items.append(f"**Random seeds**: {', '.join(str(s) for s in seeds)}")
    runs = sorted({r["num_runs"] for r in bundle["results"] if r.get("num_runs")})
    if runs:
        items.append(f"**Repeated runs**: {', '.join(str(n) for n in runs)}")

    if run.get("git_hash"):
        items.append(f"**Harness commit**: `{run['git_hash']}`")
    runtime = _duration(run.get("runtime_seconds"))
    if runtime:
        items.append(f"**Evaluation runtime**: {runtime}")
    items.append(f"**Artifacts**: `{run['artifact_root']}`")

    return "\n".join(f"- {item}" for item in items)


def render_uncertainty(bundle: dict) -> str:
    has_stat = any(
        r.get(k) is not None
        for r in bundle["results"]
        for k in ("stderr", "stddev", "prompt_sensitivity")
    )
    if not has_stat:
        return (
            "The harness reported no dispersion statistics for this run: the scores below "
            "are single point estimates with no standard error, and the run was not "
            "repeated across seeds or prompt variants."
        )

    varied = _varied(bundle)
    rows = [
        "| Benchmark | Metric | Value | Std. error | Std. dev. | Runs |",
        "|---|---|---|---|---|---|",
    ]
    for r in bundle["results"]:
        rows.append(
            f"| {_cell(_label(r, varied))} | {_cell(r['metric'])} | {_value_cell(r)} | "
            f"{_num(r.get('stderr'))} | {_num(r.get('stddev'))} | {_cell(r.get('num_runs'))} |"
        )
    body = ["\n".join(rows)]

    sensitivity = [r for r in bundle["results"] if r.get("prompt_sensitivity") is not None]
    if sensitivity:
        parts = ", ".join(
            f"{_cell(r['benchmark'])} {_num(r['prompt_sensitivity'], 2)} percentage points"
            for r in sensitivity
        )
        body.append(
            f"**Prompt sensitivity** (spread of the score across semantically equivalent "
            f"prompt phrasings, from `robust_eval`): {parts}. This is a measure of how much "
            "the reported score depends on prompt wording rather than on model capability."
        )
    body.append(
        "Standard errors and standard deviations are reported by the harness; they are not "
        "recomputed here."
    )
    return "\n\n".join(body)


def render_evaluation_results(bundle: dict) -> str:
    varied = _varied(bundle)
    rows = ["| Benchmark | Metric | Value | Std. error | Samples |", "|---|---|---|---|---|"]
    percent_scaled = False
    for r in bundle["results"]:
        if r.get("scale") == "percent":
            percent_scaled = True
        samples = f"{r['num_samples']:,}" if r.get("num_samples") is not None else "—"
        if r.get("is_partial"):
            samples += " *(partial)*"
        rows.append(
            f"| {_cell(_label(r, varied))} | {_cell(r['metric'])} | {_value_cell(r)} | "
            f"{_num(r.get('stderr'))} | {samples} |"
        )
    body = ["\n".join(rows)]

    if any(r.get("scale") == "raw" for r in bundle["results"]):
        body.append(
            "† Not a rate. This metric is reported in the harness's own units "
            "(for example perplexity, BLEU, token counts or latency) and is shown "
            "unchanged; it must not be read as a fraction or a percentage."
        )

    if percent_scaled:
        body.append(
            "Values are fractions in [0, 1]. This harness reports percentages natively; "
            "scores were divided by 100 on ingest and the original values are retained in "
            "the eval bundle."
        )

    audit = bundle.get("audit") or {}
    audit_bits = []
    if audit.get("no_answer_rate") is not None:
        audit_bits.append(f"no parseable answer on {audit['no_answer_rate'] * 100:.1f}% of items")
    if audit.get("finish_reason"):
        audit_bits.append(
            "finish reasons "
            + ", ".join(f"{k}={v}" for k, v in sorted(audit["finish_reason"].items()))
        )
    if audit.get("status_codes"):
        audit_bits.append(
            "HTTP status " + ", ".join(f"{k}={v}" for k, v in sorted(audit["status_codes"].items()))
        )
    if audit.get("avg_latency_ms") is not None:
        audit_bits.append(f"mean latency {audit['avg_latency_ms']:.0f} ms")
    if audit_bits:
        body.append(f"**Run diagnostics**: {'; '.join(audit_bits)}.")

    runtime = _duration(bundle["run"].get("runtime_seconds"))
    if runtime:
        body.append(f"Evaluation runtime: {runtime}.")
    return "\n\n".join(body)


RENDERERS = {
    SECTION_DATA: render_evaluation_data,
    SECTION_PROCEDURE: render_evaluation_procedure,
    SECTION_UNCERTAINTY: render_uncertainty,
    SECTION_RESULTS: render_evaluation_results,
}


def render_sections(bundle: dict) -> dict[str, str]:
    """Render every card section as a complete, anchored markdown block."""
    notes = _notes(bundle)
    provenance = _provenance_line(bundle)
    out: dict[str, str] = {}
    for name in SECTION_ORDER:
        parts = [ANCHOR]
        # Caveats belong where the numbers are read, not only in a footnote.
        if name in (SECTION_DATA, SECTION_RESULTS) and notes:
            parts.extend(notes)
        parts.append(RENDERERS[name](bundle))
        parts.append(provenance)
        out[name] = "\n\n".join(parts)
    return out


def render_metrics_frontmatter(bundle: dict) -> list[str]:
    """`benchmark/metric` entries for the card's `metrics:` frontmatter list.

    This form is what the Jekyll `model.html` layout renders via `page.metrics`
    and what `generate_model_inventory.py` exports, so no BPSW-side change is
    needed to surface them.
    """
    seen: list[str] = []
    for r in bundle["results"]:
        entry = f"{r['benchmark']}/{r['metric']}"
        if entry not in seen:
            seen.append(entry)
    return seen


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("bundle", type=Path)
    ap.add_argument("--section", choices=[s.replace(" ", "-") for s in SECTION_ORDER])
    ap.add_argument("--metrics", action="store_true", help="print frontmatter metrics entries only")
    args = ap.parse_args(argv)

    bundle = json.loads(args.bundle.read_text(encoding="utf-8"))

    if args.metrics:
        for entry in render_metrics_frontmatter(bundle):
            print(f"    - {entry}")
        return 0

    sections = render_sections(bundle)
    if args.section:
        wanted = args.section.replace("-", " ")
        print(sections[wanted])
        return 0
    for name in SECTION_ORDER:
        print(f"## {name.title()}\n")
        print(sections[name])
        print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
