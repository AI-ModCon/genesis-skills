#!/usr/bin/env python3
"""Render an eval bundle into BPSW model-card sections.

This is the *model-card* renderer. It is deliberately one of several possible
renderers over the same bundle: SIM wants drift-relevant series, SAFE wants the
failure and refusal tail. Those belong in sibling scripts reading the same
`references/eval-bundle.schema.json` contract, not in here.

Every number emitted is copied from a bundle field. Nothing is recomputed.

Usage:
    render_card_sections.py <bundle.json> [--section evaluation-results]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

# The visible heading that anchors generated content inside a card section.
# Deliberately NOT an HTML comment: modcon-bpsw's sync_and_classify_cards.py
# strips HTML/YAML comments, which would silently destroy the anchor and break
# idempotent re-runs.
ANCHOR = "### Automated benchmark results"

SECTION_DATA = "evaluation data"
SECTION_PROCEDURE = "evaluation procedure"
SECTION_UNCERTAINTY = "uncertainty quantification"
SECTION_RESULTS = "evaluation results"

SECTION_ORDER = [SECTION_DATA, SECTION_PROCEDURE, SECTION_UNCERTAINTY, SECTION_RESULTS]


def _cell(value) -> str:
    """Table-safe string: pipes would break the row."""
    if value is None:
        return "—"
    return str(value).replace("|", "\\|").replace("\n", " ")


def _num(value, places: int = 4) -> str:
    if value is None:
        return "—"
    return f"{value:.{places}f}"


def _value_cell(row: dict) -> str:
    """Format a score. Non-rate metrics keep the harness's own units and are
    marked, so a perplexity of 12.5 is never read as a fraction."""
    if row.get("value") is None:
        return "—"
    if row.get("scale") == "raw":
        return f"{row['value']:g} †"
    return _num(row["value"])


def _duration(seconds) -> str | None:
    if seconds is None:
        return None
    seconds = int(round(float(seconds)))
    if seconds < 60:
        return f"{seconds}s"
    if seconds < 3600:
        return f"{seconds // 60}m {seconds % 60}s"
    return f"{seconds // 3600}h {(seconds % 3600) // 60}m"


def _varied(bundle: dict) -> set[str]:
    """Benchmarks that were run across several prompt variants."""
    return {r["benchmark"] for r in bundle["results"] if r.get("variant")}


def _label(row: dict, varied: set[str] | None = None) -> str:
    name = row["benchmark"]
    if row.get("variant"):
        return f"{name} ({row['variant']})"
    # A variant-less row for a benchmark that *has* variants is the aggregate;
    # unlabelled it is indistinguishable from a single-variant score.
    if varied and name in varied:
        return f"{name} (aggregate)"
    return name


def _provenance_line(bundle: dict) -> str:
    run = bundle["run"]
    parts = [run["harness"]]
    if run.get("harness_version"):
        parts.append(f"v{run['harness_version']}")
    if run.get("framework"):
        parts.append(f"via {run['framework']}")
    origin = " ".join(parts)
    tail = f" on {run['date'][:10]}" if run.get("date") else ""
    return (
        f"*Generated by `card-eval-updater` from {origin} output{tail}. "
        f"Re-run the tool to refresh; do not edit this block by hand.*"
    )


def _partial_note(bundle: dict) -> str | None:
    partial = [r for r in bundle["results"] if r.get("is_partial")]
    if not partial:
        return None
    return (
        "> **Partial run.** These figures come from a sample-limited evaluation and are "
        "not comparable with full-benchmark results. They are recorded for traceability "
        "only and should not be cited as the model's benchmark performance."
    )


def _judge_note(bundle: dict) -> str | None:
    judges = (bundle.get("audit") or {}).get("llm_judge_names")
    if not judges:
        return None
    return (
        f"> **LLM-judged.** Scores were assigned by an LLM judge ({', '.join(judges)}) "
        "rather than by exact match, and inherit that judge's biases and error rate."
    )


def _unverified_model_note(bundle: dict) -> str | None:
    model = bundle["model"]
    if model.get("id_provenance") == "user" and model.get("id"):
        return (
            f"> **Model identity supplied by the operator.** `{model['id']}` was not "
            "recorded in the harness output and could not be verified against the run."
        )
    if not model.get("id"):
        return "> **Model identity unknown.** The harness output records no model identifier."
    return None


def _notes(bundle: dict) -> list[str]:
    return [
        note
        for note in (_partial_note(bundle), _judge_note(bundle), _unverified_model_note(bundle))
        if note
    ]


